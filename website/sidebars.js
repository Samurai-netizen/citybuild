const missing = listPages().filter(
  (p) => !explicit.has(docId(p)) && !listedFolders.some((dir) => p.startsWith(`${dir}/`)),
);
if (missing.length > 0) {
  throw new Error(
    `These pages are not in the handbook sidebar: ${missing.join(', ')}. ` +
      'Add each to website/sidebars.js (core-instructions/19-change-recipes.md → "New documentation page").',
  );
}

