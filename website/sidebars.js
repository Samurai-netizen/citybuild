// The handbook's table of contents: the book order of the repository's docs, which stay where they are.
// Every page must appear here (directly or through a listed folder); the build fails otherwise, naming the page.
// Adding a page: core-instructions/19-change-recipes.md → "New documentation page".
const {listPages, docId} = require('./docs-set');
const {shortLabel} = require('./sidebar-items');

const explicit = new Set();
const listedFolders = [];

/** One page, by its repository path. */
function page(relPath, label) {
  if (!listPages().includes(relPath)) {
    throw new Error(`sidebars.js names ${relPath}, which is not a handbook page (missing, or not listed in website/docs-set.js)`);
  }
  explicit.add(docId(relPath));
  return {type: 'doc', id: docId(relPath), label: label || shortLabel(relPath)};
}

/** A spec of core-instructions/ by its number (`'04'`). */
function spec(number) {
  const relPath = listPages().find((p) => p.startsWith(`core-instructions/${number}-`));
  if (!relPath) throw new Error(`sidebars.js: no core-instructions/${number}-*.md`);
  return page(relPath);
}

/** A folder whose README is the category page and whose other pages are listed automatically. */
function folder(label, dirName) {
  listedFolders.push(dirName);
  return {
    type: 'category',
    label,
    link: {type: 'doc', id: page(`${dirName}/README.md`).id},
    items: [{type: 'autogenerated', dirName}],
  };
}

const chapter = (label, items) => ({type: 'category', label, collapsed: false, items});

